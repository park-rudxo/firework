-- 예전에 보이던 응답을 다시 감추지 않는다 — 단, 사람이 근거를 확인했을 때만.
--
-- 앞선 마이그레이션(20260910072918)은 설문마다 3의 배수만큼만 열어뒀다.
-- 그게 문제다. 예전 구현에서는 3건 이상이면 전부 보였으므로, 5건짜리 설문에서
-- 제작자는 이미 5건을 다 읽었다. 거기서 3건만 남기면 2건이 "안 본 것" 이 되고,
-- 나중에 새 응답 1건이 그 2건과 함께 열리는 순간 —
-- 제작자는 이미 아는 2건을 빼고 남은 하나가 새 응답임을 바로 안다.
-- 감추려던 것이 오히려 신규 응답을 지목하게 만든다.
--
-- ── 그런데 여기서 자동으로 열 수는 없다 ───────────────────────────────
--
-- "전부 열면 된다" 는 **지금 안 열려 있는 행이 전부 예전부터 있던 행일 때만** 옳다.
-- 앞 마이그레이션이 적용된 뒤 묶음 규칙을 아는 앱이 응답을 하나라도 받았다면 그
-- 전제가 깨진다.
--
--     기존 3건(전부 공개) + 그 뒤 들어온 새 응답 1건(미공개)
--     → 전부 열면 제작자 화면이 3건에서 4건이 되고, 늘어난 하나가 곧 새 응답이다.
--
-- 이 마이그레이션이 막으려던 바로 그 노출을 이 마이그레이션이 만들어내는 셈이다.
--
-- 응답 행에는 시간도 순번도 없다. 그게 익명성의 근거이므로 앞으로도 넣지 않는다.
-- 따라서 "예전 행" 과 "새 행" 은 **데이터로 구분할 방법이 없다.**
--
-- 적용 시각 차이로 갈음해 보려 했지만 그것도 근거가 못 된다. 앞 마이그레이션이 방금
-- 끝났더라도 그 사이에 같은 DB 를 보는 앱(다른 배포, 로컬 next dev)이 응답을 받을 수
-- 있고, 그러면 열어서는 안 될 행을 연다. 시간 창을 어디에 두든 그 안에서 새 응답이
-- 들어올 수 있으므로, 좁힐 수는 있어도 닫을 수는 없다.
--
-- 그래서 추정하지 않는다. 바꿀 행이 남아 있으면 배포를 세우고 사람이 정한다.
-- 잘못 연 응답은 되돌릴 수 없다 — 다시 감추는 것 자체가 "그 한 건이 새 응답" 이라는
-- 신호이기 때문이다. 확인한 뒤 여는 방법은 docs/recovery/03-preserve-existing-revealed.sql 에 있다.
DO $$
DECLARE
  at_risk_surveys integer;
BEGIN
  -- 이 마이그레이션이 실제로 바꿀 행이 있는 설문.
  -- 예전 기준(3건 이상)으로는 전부 보였는데 아직 안 열린 행이 남아 있는 것들이다.
  SELECT count(*) INTO at_risk_surveys
  FROM (
    SELECT "surveyId"
    FROM "survey_response"
    GROUP BY "surveyId"
    HAVING count(*) >= 3 AND count(*) FILTER (WHERE NOT "revealed") > 0
  ) s;

  -- 바꿀 것이 없으면 할 일도 없다.
  -- 응답이 없는 DB — 새로 만든 DB, CI, 2026-09-11 확인 기준 운영 — 는 전부 여기서 끝난다.
  IF at_risk_surveys = 0 THEN
    RETURN;
  END IF;

  RAISE EXCEPTION
    '설문 % 개에 아직 열리지 않은 응답이 남아 있습니다.', at_risk_surveys
    USING
      DETAIL =
        '예전 구현에서 3건 이상이면 전부 보였으므로 이 행들은 원래 공개돼 있었을 수 있습니다. '
        || '그러나 20260910072918 적용 이후에 들어온 새 응답도 같은 모습이고, 응답 행에는 시간도 순번도 '
        || '없어 둘을 구분할 수 없습니다. 여기서 전부 열면 늘어난 한 건이 곧 신규 응답이 됩니다.',
      HINT =
        '선택지: (1) 이 DB 에 20260910072918 적용 이후 새 응답이 들어온 적이 없음을 배포/접속 이력으로 '
        || '확인한 뒤 docs/recovery/03-preserve-existing-revealed.sql 을 직접 실행한다. '
        || '(2) 검증용 DB 라면 설문 응답을 비우고 다시 적용한다. '
        || '(3) 근거가 없으면 열지 않은 채 두고 docs/HANDOFF.md 에 적어 사람이 정한다.';
END $$;
